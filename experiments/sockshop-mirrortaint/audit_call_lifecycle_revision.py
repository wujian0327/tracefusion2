#!/usr/bin/env python3
"""Final bookkeeping/integrity gate; does not substitute for semantic oracles."""
import argparse,json,subprocess
from pathlib import Path
from run_planned_service import ROOT,HERE,load,save,sha


def audit(root):
    frozen=load(root/'algorithm-freeze.json');commit=frozen['algorithm_commit']
    for filename,digest in frozen['core_sources'].items():
        assert sha(ROOT/filename)==digest,filename
        import hashlib
        assert hashlib.sha256(subprocess.check_output(['git','show',commit+':'+filename],cwd=ROOT)).hexdigest()==digest,filename
    manifest=load(root/'base-build/build.json');assert sha(root/'base-build/distributed-observer.jar')==frozen['agent_sha256']
    for role,digest in frozen['original_jars'].items():assert sha(root/'base-build'/role/'original.jar')==digest
    positive={}
    for build,role,profile in (('legacy-build','orders','mapped-reduction'),('legacy-build','shipping','identity-return'),('legacy-build','station','field-copy'),('price-build','basic','collection-computation')):
        p=root/build/role/'plan.json';assert load(p)['profile']==profile
        positive[role]={'profile':profile,'plan_sha256':sha(p)}
    save(root/'historical-positive-controls.json',{'passed':4,'selected':4,'controls':positive,'scope':'Plans generated by the current frozen builder; business captures separately verified below'})
    checks={}
    for name in ('semantics-complete','read-semantics','binding-semantics','collection-controls','basic-mixed-same-config'):
        assert load(root/name/'results.json')['all_passed'];checks[name]=sha(root/name/'results.json')
    for name in ('bound-calibration-audit.json','price-raw-toggle-audit.json','train-repeat-call-protection.json','offline-memory-audit.json','cost-audit.json'):
        assert load(root/name)['all_passed'];checks[name]=sha(root/name)
    basic=load(root/'basic-mixed-same-config/results.json')['mixed_development_regressions'];assert len(basic)==2
    for r in basic:
        assert (r['requests'],r['target_instances'],r['known'],r['unknown'],r['evidence_invalid'],r['oracle_unavailable'],r['N/A_requests'])==(16,15,0,15,0,0,1)
        assert load(root/'basic-mixed-same-config'/r['id']/'same-configuration.json')['same_plan_except_read_effect_lifecycle_protocol']
    for app,expected in (('sockshop',(198,258)),('trainticket',(31,30))):
        s=load(root/'historical-business'/app/'field-results.json')['summary']
        assert (s['queries'],s['exact'],s['tp'],s['fp'],s['fn'],s['unknown'])==(expected[0],expected[0],expected[1],0,0,0)
    for mode in ('full','selective'):
        s=load(root/'price-business'/mode/'evaluation.json');assert (s['queries'],s['exact'],s['tp'],s['fp'],s['fn'],s['unknown'])==(38,38,92,0,0,0)
    assert load(root/'cart-create-guard/checks.json')['all_passed']
    memory=load(root/'offline-memory-audit.json');assert memory['replay_count']==30 and memory['originals_unchanged']
    assert all(sha(Path(p))==digest for p,digest in memory['original_file_sha256'].items())
    cost=load(root/'cost-audit.json');assert cost['performance_eligible'] and cost['independent_deployments']==45
    expected={'cart':(1350,1350),'train':(900,900),'price':(1800,4330)}
    for kind,result in cost['results'].items():
        for mode in ('full','selective'):
            pops=result['populations'][mode];assert len(pops)==5
            assert sum(p['queries'] for p in pops)==sum(p['exact'] for p in pops)==expected[kind][0]
            assert sum(p['tp'] for p in pops)==expected[kind][1]
            assert all(p['unknown']==p['fp']==p['fn']==0 for p in pops)
    assert len(load(root/'static-planning-final/results.json')['measurements'])==15
    assert 'Ran 32 tests' in (root/'logs/14-final-unit-regression.log').read_text()
    projects=set()
    for p in root.rglob('cleanup.json'):
        r=load(p);assert r['returncode']==0,p
        if r.get('project'):projects.add(r['project'])
    for p in root.rglob('run.json'):
        r=load(p)
        if r.get('project'):projects.add(r['project'])
    raw=subprocess.check_output(['docker','ps','--format','{{.Names}}\t{{.Label "com.docker.compose.project"}}'],text=True)
    active=[line for line in raw.splitlines() if line.split('\t')[-1] in projects];assert not active,active
    result={'all_passed':True,'scope':'Integrity and bookkeeping; underlying original-program runs and independent oracles supply correctness evidence','algorithm_commit':commit,'core_source_hashes_match_commit_and_freeze':True,'original_jars_unchanged':True,'basic_same_configuration':basic,'old_initial_missing_conversion_declaration_retained':True,'strict_same_config_regression_after_costs':True,'cost_deployments':45,'memory_replays':30,'memory_originals_unchanged':True,'static_planning_repeats':15,'unit_checks':32,'task_projects_without_running_containers':len(projects),'active_task_containers':active,'evidence_sha256':checks,'auditor_sha256':sha(Path(__file__))}
    save(root/'final-audit.json',result);save(root/'logs/15-final-audit.json',result);print('Final lifecycle revision audit passed',flush=True)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--root',type=Path,required=True);audit(p.parse_args().root.resolve())
